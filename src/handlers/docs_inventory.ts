/**
 * What is vendored in `src/docs/`: the ZQL and zega documentation, `docs/*.md` of zegadb/zega, copied byte for
 * byte so `zega mcp` (the `docs` group) can search it with no network. Like the explorer's files, three things
 * belong together and are made by functions the update script and the test both use: the list (`listFiles`),
 * the SHA-256 of each (`inventoryOf`, from `explorer_inventory.ts`) and the module that embeds them.
 */

/** The text of `src/docs/pages.ts`: every page imported as text (a compiled executable carries it inside), keyed by its name. */
export function pagesModule(files: string[]): string {
    const pages = files.filter((file) => file.endsWith('.md'))
    const lines = [
        '// @ts-nocheck: TypeScript would type each import as the module it names; here every one is the page\'s text.',
        '// Generated by `bun run docs:update` from the files beside it: do not edit.',
        '',
    ]
    pages.forEach((file, index) => lines.push(`import p${index} from './pages/${file}' with { type: 'text' }`))
    lines.push('', 'export const PAGES = {')
    pages.forEach((file, index) => lines.push(`    ${JSON.stringify(file.replace(/\.md$/, ''))}: p${index},`))
    lines.push('} as unknown as Record<string, string>', '')
    return lines.join('\n')
}
