/**
 * What is vendored in `src/explorer/`: the focused explorer page, built in zegadb/zega
 * (`npm run build:cli` in its `browser/`, which makes `dist-cli/` from the same source as the
 * zega.dev playground without its links and samples) and copied here byte for byte.
 *
 * Three things belong together and one function here makes each of them, so the update script,
 * the test and the gate (`inventory.json` and `files.ts` must match the files) all use these:
 * the list of files, their SHA-256, and the TypeScript module that embeds them (a compiled
 * executable carries them inside; `import ... with { type: 'file' }` is how Bun embeds a file).
 */
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

export type Inventory = {
    /** The repository the files were built from. */
    source: 'zegadb/zega'
    /** The commit of that repository whose `browser/` built them. */
    commit: string
    /** Path (forward slashes, relative to `src/explorer/dist`) to its SHA-256. */
    files: Record<string, string>
}

/** Every file under `dir`, as forward-slash paths relative to it, sorted. */
export function listFiles(dir: string): string[] {
    const found: string[] = []
    const walk = (current: string): void => {
        for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
            const full = path.join(current, entry.name)
            if (entry.isDirectory()) walk(full)
            else if (entry.isFile()) found.push(path.relative(dir, full).split(path.sep).join('/'))
        }
    }
    walk(dir)
    return found.sort()
}

export function sha256(file: string): string {
    return createHash('sha256').update(fs.readFileSync(file)).digest('hex')
}

export function inventoryOf(dir: string, commit: string): Inventory {
    const files: Record<string, string> = {}
    for (const file of listFiles(dir)) files[file] = sha256(path.join(dir, file))
    return { source: 'zegadb/zega', commit, files }
}

/** The text of `src/explorer/files.ts`: every file imported as an embedded file, keyed by its path. */
export function filesModule(paths: string[]): string {
    const lines = [
        '// @ts-nocheck: TypeScript would type each import as the module it names (a .js, a .wasm, a .css); here every one is a path.',
        '// Generated by `bun run explorer:update` from the files beside it: do not edit.',
        '// Each import is a file Bun embeds in a compiled executable; the value is a path `Bun.file` reads.',
        '',
    ]
    paths.forEach((file, index) => lines.push(`import f${index} from './dist/${file}' with { type: 'file' }`))
    lines.push('', 'export const FILES = {')
    paths.forEach((file, index) => lines.push(`    ${JSON.stringify(file)}: f${index},`))
    lines.push('} as unknown as Record<string, string>', '')
    return lines.join('\n')
}
